/*
 * Builds the SIGIL interface into something a VST3 can carry.
 *
 * Two steps, and both of them deliberately avoid touching the web app:
 *
 * 1. STAGE + EXPORT. Next reads `next.config.mjs` from the project root and has
 *    no flag to point it somewhere else, so the only way to run a second build
 *    with different options is to run it from a second root. A staging copy is
 *    assembled under native/plugin/ui-stage, with its own `output: 'export'`
 *    config, and `next build` runs there. next.config.mjs at the repo root is
 *    never read and never modified, so `pnpm build` and the Railway deploy are
 *    untouched by anything in this file.
 *
 *    The staging copy drops app/api, app/gate and the metadata image routes.
 *    Not to trim the bundle - `output: 'export'` REFUSES to build a route
 *    handler that is not declared static, and those five routes are exactly
 *    that. None of them mean anything in a plugin: there is no passcode gate on
 *    a thing you already installed, and nothing is going to render a social card
 *    for an audio unit.
 *
 *    node_modules is not copied. Staging lives inside the repo, so Node's own
 *    upward resolution finds the root install - which also means a symlink,
 *    which Turbopack rejects as pointing outside its filesystem root, is not
 *    needed.
 *
 * 2. EMBED. The exported tree is written out as one generated C++ file holding
 *    the bytes and a path -> {mime, bytes} table, which the editor's
 *    ResourceProvider answers requests from. No file paths at runtime, no
 *    network, nothing to install alongside the .vst3.
 */
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const stage = join(root, 'native', 'plugin', 'ui-stage');
const exported = join(stage, 'dist');
const generated = join(root, 'native', 'plugin', 'ui-bundle.cpp');

/** Routes `output: 'export'` cannot build, none of which a plugin wants. */
const DROP = [
  'app/api',
  'app/gate',
  'app/icon.tsx',
  'app/apple-icon.tsx',
  'app/opengraph-image.tsx',
  'app/twitter-image.tsx',
  'app/manifest.ts',
];

const MIME = new Map([
  ['.html', 'text/html; charset=utf-8'],
  ['.js', 'text/javascript; charset=utf-8'],
  ['.mjs', 'text/javascript; charset=utf-8'],
  ['.css', 'text/css; charset=utf-8'],
  ['.json', 'application/json; charset=utf-8'],
  ['.txt', 'text/plain; charset=utf-8'],
  ['.svg', 'image/svg+xml'],
  ['.png', 'image/png'],
  ['.jpg', 'image/jpeg'],
  ['.jpeg', 'image/jpeg'],
  ['.webp', 'image/webp'],
  ['.ico', 'image/x-icon'],
  ['.woff', 'font/woff'],
  ['.woff2', 'font/woff2'],
  ['.ttf', 'font/ttf'],
  ['.wasm', 'application/wasm'],
  ['.map', 'application/json; charset=utf-8'],
]);

function mimeFor(path) {
  const dot = path.lastIndexOf('.');
  return (dot < 0 ? undefined : MIME.get(path.slice(dot).toLowerCase()))
    ?? 'application/octet-stream';
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

// ---------------------------------------------------------------------------
// 1. Stage and export.
// ---------------------------------------------------------------------------
console.log('[plugin-ui] staging');
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });

for (const dir of ['app', 'src', 'public']) {
  cpSync(join(root, dir), join(stage, dir), { recursive: true });
}
for (const name of ['tsconfig.json', 'postcss.config.mjs']) {
  cpSync(join(root, name), join(stage, name));
}
for (const drop of DROP) {
  rmSync(join(stage, ...drop.split('/')), { recursive: true, force: true });
}

/*
 * `distDir` rather than the default so the export lands somewhere obviously
 * disposable, and `reactStrictMode` off because Strict Mode's deliberate double
 * mount would have the bridge ask the plugin for its state twice on every
 * editor open.
 */
writeFileSync(join(stage, 'next.config.mjs'), `/* GENERATED by scripts/build-plugin-ui.mjs. */
export default {
  output: 'export',
  distDir: 'dist',
  images: { unoptimized: true },
  reactStrictMode: false,
};
`);
writeFileSync(join(stage, 'package.json'), JSON.stringify({
  name: 'sigil-plugin-ui', private: true, type: 'module',
}, null, 2));

console.log('[plugin-ui] next build (static export)');
execFileSync(process.execPath, [join(root, 'node_modules', 'next', 'dist', 'bin', 'next'), 'build'], {
  cwd: stage,
  stdio: 'inherit',
  env: { ...process.env, NEXT_TELEMETRY_DISABLED: '1' },
});

if (!existsSync(join(exported, 'index.html'))) {
  throw new Error(`no index.html in ${exported}: the export did not produce a page`);
}

// ---------------------------------------------------------------------------
// 2. Embed.
// ---------------------------------------------------------------------------
const files = walk(exported)
  .map((full) => ({ full, path: '/' + relative(exported, full).split(sep).join('/') }))
  // The .txt siblings are Next's RSC payloads for client-side navigation. There
  // is exactly one page here and nothing navigates, so they are dead weight.
  .filter((f) => !f.path.endsWith('.txt'))
  .sort((a, b) => (a.path < b.path ? -1 : 1));

const sizes = new Map(files.map((f) => [f.path, statSync(f.full).size]));

const out = [];
out.push('// GENERATED by scripts/build-plugin-ui.mjs. Do not edit, do not commit.');
out.push('#include "ui-bundle.h"');
out.push('');
out.push('#include <cstring>');
out.push('');
out.push('namespace sigil::ui {');
out.push('namespace {');

let total = 0;
files.forEach((file, i) => {
  const bytes = readFileSync(file.full);
  total += bytes.length;
  /*
   * String literals rather than a brace-initialised array: clang parses them an
   * order of magnitude faster at this size, and the escaping is exhaustive
   * (every byte, always three octal digits) so no character can end a literal
   * early or extend an escape into the next byte.
   */
  const chunks = [];
  for (let at = 0; at < bytes.length; at += 4096) {
    const slice = bytes.subarray(at, at + 4096);
    let s = '';
    for (const b of slice) s += '\\' + b.toString(8).padStart(3, '0');
    chunks.push(`  "${s}"`);
  }
  if (chunks.length === 0) chunks.push('  ""');
  out.push(`// ${file.path} (${bytes.length} bytes)`);
  out.push(`const unsigned char kData${i}[] =`);
  out.push(chunks.join('\n') + ';');
  out.push('');
});

out.push('}  // namespace');
out.push('');
out.push('const Asset kAssets[] = {');
files.forEach((file, i) => {
  out.push(`    {"${file.path}", "${mimeFor(file.path)}", kData${i}, ${sizes.get(file.path)}},`);
});
out.push('};');
out.push('');
out.push(`const int kAssetCount = ${files.length};`);
out.push('');
out.push(`const Asset* findAsset(const char* path) {
  if (path == nullptr) return nullptr;
  const char* query = std::strchr(path, '?');
  const std::size_t len = query == nullptr ? std::strlen(path) : static_cast<std::size_t>(query - path);
  const char* wanted = path;
  std::size_t wantedLen = len;
  if (len == 0 || (len == 1 && path[0] == '/')) {
    wanted = "/index.html";
    wantedLen = 11;
  }
  for (int i = 0; i < kAssetCount; ++i) {
    if (std::strlen(kAssets[i].path) != wantedLen) continue;
    if (std::strncmp(kAssets[i].path, wanted, wantedLen) == 0) return &kAssets[i];
  }
  return nullptr;
}`);
out.push('');
out.push('}  // namespace sigil::ui');
out.push('');

writeFileSync(generated, out.join('\n'));

/*
 * The staging tree is a full copy of app/ and src/, and leaving it behind means
 * every grep in this repository finds two of everything. The generated C++ is
 * self-contained, so nothing needs it after this point.
 */
rmSync(stage, { recursive: true, force: true });

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
console.log(`[plugin-ui] embedded ${files.length} files, ${kb(total)} -> ${relative(root, generated)}`);
for (const f of files) {
  console.log(`  ${f.path}  ${kb(sizes.get(f.path))}`);
}

#!/usr/bin/env node
/**
 * Emits native/src/sigil-descriptors.h from the REAL TypeScript descriptors.
 *
 * Parameter ids, ranges, defaults and ordering are not retyped by hand: they are
 * read out of src/dsp/*-descriptor.ts through the same esbuild loader the golden
 * generator uses. Re-run this whenever a descriptor changes; the C++ side is
 * then wrong only if the generator is wrong, not if somebody mistyped a number.
 *
 * Reads src/, writes only native/. Never writes TypeScript.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadDsp, ROOT } from '../../scripts/golden/harness.mjs';

const EXPORTS = `
export { ENGINES, DEFAULT_ENGINE_ID } from '@/dsp/registry';
export { FX_DESCRIPTOR } from '@/dsp/fx-descriptor';
export { FX_MAGIC_DESCRIPTOR } from '@/dsp/fx-magic-descriptor';
export { ENGINE_PARAM_BASE, FX_PARAM_BASE, MAGIC_PARAM_BASE } from '@/audio/param-space';
export { PATCH_FORMAT_VERSION } from '@/audio/patch-format';
`;

const D = await loadDsp(EXPORTS);

const cstr = (s) => JSON.stringify(String(s));
/** Print a double with enough digits to round-trip exactly. */
const num = (v) => {
  if (!Number.isFinite(v)) throw new Error(`non-finite descriptor value: ${v}`);
  const s = Number(v).toPrecision(17);
  if (Number(s) !== v) throw new Error(`lossy print of ${v}`);
  return String(Number(s)) === String(v) ? `${v}` : s;
};

function paramRows(params, name) {
  return params.map((p) => {
    if (!(p.min <= p.default && p.default <= p.max)) {
      throw new Error(`${name}.${p.id}: default ${p.default} outside [${p.min}, ${p.max}]`);
    }
    const steps = typeof p.steps === 'number' ? p.steps : 0;
    return `    {${cstr(p.id)}, ${cstr(p.name)}, ${cstr(p.group)}, ${cstr(p.unit)}, `
      + `${num(p.min)}, ${num(p.max)}, ${num(p.default)}, ${cstr(p.curve)}, ${steps}},`;
  }).join('\n');
}

const engines = D.ENGINES.map((e) => e.descriptor);
const out = [];
out.push(`// GENERATED by native/tools/gen-descriptors.mjs from the TypeScript descriptors.
// DO NOT EDIT BY HAND. Regenerate with: node native/tools/gen-descriptors.mjs
#pragma once

#include <cstddef>

namespace sigil {
namespace desc {

struct ParamDesc {
  const char* id;
  const char* name;
  const char* group;
  const char* unit;
  double min;
  double max;
  double def;
  const char* curve;
  int steps;  // 0 when the descriptor gives none
};

struct EngineDesc {
  const char* id;
  const char* name;
  const ParamDesc* params;
  int count;
};

/** src/audio/param-space.ts */
constexpr int kEngineParamBase = ${D.ENGINE_PARAM_BASE};
constexpr int kFxParamBase = ${D.FX_PARAM_BASE};
constexpr int kMagicParamBase = ${D.MAGIC_PARAM_BASE};
/** src/audio/patch-format.ts */
constexpr int kPatchFormatVersion = ${D.PATCH_FORMAT_VERSION};
constexpr const char* kDefaultEngineId = ${cstr(D.DEFAULT_ENGINE_ID)};
`);

for (const e of engines) {
  const sym = e.id.replace(/[^A-Za-z0-9]/g, '_');
  out.push(`inline constexpr ParamDesc kParams_${sym}[] = {\n${paramRows(e.params, e.id)}\n};`);
}
out.push(`inline constexpr ParamDesc kParams_fx[] = {\n${paramRows(D.FX_DESCRIPTOR.params, 'fx')}\n};`);
out.push(`inline constexpr ParamDesc kParams_magic[] = {\n${paramRows(D.FX_MAGIC_DESCRIPTOR.params, 'magic')}\n};`);

out.push(`
/** Engine order is src/dsp/registry.ts order. Load-bearing: the plugin's
 *  engine-select parameter is an index into this array. */
inline constexpr EngineDesc kEngines[] = {
${engines.map((e) => {
  const sym = e.id.replace(/[^A-Za-z0-9]/g, '_');
  return `    {${cstr(e.id)}, ${cstr(e.name)}, kParams_${sym}, ${e.params.length}},`;
}).join('\n')}
};
constexpr int kEngineCount = ${engines.length};

inline constexpr EngineDesc kFxDesc = {${cstr(D.FX_DESCRIPTOR.id)}, ${cstr(D.FX_DESCRIPTOR.name)}, kParams_fx, ${D.FX_DESCRIPTOR.params.length}};
inline constexpr EngineDesc kMagicDesc = {${cstr(D.FX_MAGIC_DESCRIPTOR.id)}, ${cstr(D.FX_MAGIC_DESCRIPTOR.name)}, kParams_magic, ${D.FX_MAGIC_DESCRIPTOR.params.length}};

}  // namespace desc
}  // namespace sigil`);

const path = join(ROOT, 'native/src/sigil-descriptors.h');
writeFileSync(path, out.join('\n') + '\n');
console.error(`wrote ${path}`);
console.error(`engines: ${engines.map((e) => `${e.id}(${e.params.length})`).join(' ')}`);
console.error(`fx: ${D.FX_DESCRIPTOR.params.length}  magic: ${D.FX_MAGIC_DESCRIPTOR.params.length}`);
